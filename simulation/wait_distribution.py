"""Waiting-time distribution of the decided policy: tails, long waits and the cost per extra patient.

The mean wait hides the patients who wait long. This script simulates the same sessions with fixed
intervals and with the decided rule (common random numbers) and looks at every single patient:
percentiles, shares above 5, 10 and 15 minutes, who waits (overbooked slots or not) and what one
extra patient costs. Output: docs/waiting-time-distribution.md

    python simulation/wait_distribution.py [--risks PATH] [--quick]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import clinic_sim as cs
import experiments as ex
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
REPORT = HERE.parent / "docs" / "waiting-time-distribution.md"
CUTS = (5, 10, 15)


def collect(cfg, policy, reps, seed, pool):
    """Every seen patient's wait and the per-session totals."""
    rows, sessions = [], []
    for rep in range(reps):
        d = cs.draw_session(cfg, np.random.default_rng([seed, rep]), pool)
        res = cs.simulate_session(cfg, policy, d, detail=True)
        waits = [x["start"] - max(x["appointment"], x["arrival"]) for x in res["detail"]]
        for x, w in zip(res["detail"], waits, strict=True):
            rows.append({"rep": rep, "wait": w, "overbooked": x["overbooked"]})
        sessions.append(
            {
                "rep": rep,
                "seen": res["seen"],
                "total_wait": float(sum(waits)),
                "max_wait": float(max(waits, default=0.0)),
                "overtime": res["overtime"],
            }
        )
    return pd.DataFrame(rows), pd.DataFrame(sessions)


def summary(w: pd.Series) -> dict:
    out = {
        "Patients (total)": len(w),
        "Mean (min)": w.mean(),
        "Median (min)": w.median(),
        "90% (min)": w.quantile(0.90),
        "95% (min)": w.quantile(0.95),
        "99% (min)": w.quantile(0.99),
        "Longest (min)": w.max(),
    }
    for c in CUTS:
        out[f"> {c} min (%)"] = 100 * float((w > c).mean())
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--risks", type=Path, default=ex.RISKS)
    ap.add_argument("--decisions", type=Path, default=ex.DOCS / "decisions.json")
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    d = ex.load_decisions(args.decisions)
    cfg = ex.session_config(d)
    pool = pd.read_csv(args.risks)
    reps = 100 if args.quick else 3000

    fw, fs = collect(cfg, cs.fixed_interval(), reps, ex.SEED + 7, pool)
    rw, rs = collect(cfg, ex.rule_of(d), reps, ex.SEED + 7, pool)

    tab = pd.DataFrame(
        {
            "Fixed intervals": summary(fw["wait"]),
            ex.rule_name(d): summary(rw["wait"]),
            "Rule, patients in overbooked slots": summary(rw.loc[rw.overbooked, "wait"]),
            "Rule, other patients": summary(rw.loc[~rw.overbooked, "wait"]),
        }
    ).T.reset_index(names="Group")
    tab["Patients (total)"] = tab["Patients (total)"].astype(int)

    extra = rs["seen"].mean() - fs["seen"].mean()
    dwait = rs["total_wait"].mean() - fs["total_wait"].mean()
    dover = rs["overtime"].mean() - fs["overtime"].mean()
    long_f, long_r = (
        (fs["max_wait"] > d["wait_limit_min"]).mean(),
        (rs["max_wait"] > d["wait_limit_min"]).mean(),
    )
    limit = d["wait_limit_min"]
    over = 100 * float((rw["wait"] > limit).mean())
    text = f"""# Waiting-time distribution and cost–benefit (generated)

This file is generated by `simulation/wait_distribution.py`; do not edit it by hand. The settings come from `docs/decisions.json`: {ex.assumptions_line(d, cfg)}. {reps} paired sessions; every row is the wait of one **patient** (patients seen).

## 1. Distribution

{ex.md_table(tab)}

Wait = start of the consultation − max(appointment time, patient's arrival). The mean is far below the {limit} min limit, but what matters is how many minutes single patients wait.

- Under the rule, **{over:.2f}%** of the patients wait longer than {limit} min.
- At least one patient of a session waits longer than {limit} min: {100 * long_f:.1f}% with fixed intervals, {100 * long_r:.1f}% under the rule (per session).
- The long waits fall mostly on the patients in overbooked slots (third row).

## 2. Cost per extra patient (per session)

| Item | Fixed intervals | Decided setting | Difference |
|---|---|---|---|
| Patients seen | {fs["seen"].mean():.2f} | {rs["seen"].mean():.2f} | {extra:+.2f} |
| Total patient waiting time (patient-min) | {fs["total_wait"].mean():.1f} | {rs["total_wait"].mean():.1f} | {dwait:+.1f} |
| Overtime (min) | {fs["overtime"].mean():.2f} | {rs["overtime"].mean():.2f} | {dover:+.2f} |

The rule sees **{extra:.2f} extra patients** per session; the cost is **{dwait:.1f} patient-minutes** of extra waiting in total and **{dover:.2f} min** of overtime. Per extra patient that is about **{dwait / extra:.1f} min** of total waiting and about **{dover / extra:.2f} min** of overtime.

These figures depend on the simulation assumptions (across consultation times of 5–10 min the increase in waiting ranges from 0.4 to 2.2 min, `docs/experiment-results.md` section 4).
"""
    REPORT.write_text(text, encoding="utf-8")
    print("Saved:", REPORT)
    print(tab.round(2).to_string(index=False))


if __name__ == "__main__":
    main()
